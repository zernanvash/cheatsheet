def hex_dump(data, size=16):
    for i in range(0, len(data), size):
        chunk = data[i:i + size]
        
        # 1. address
        address = f"{i:08x}: "
        
        # 2. data in HEX
        hex_view = chunk.hex(' ').ljust(size * 3 - 1)
        
        # 3. data ASCII 
        ascii_view = "".join(chr(b) if 32 <= b <= 126 else "." for b in chunk)
        
        print(f"{address} {hex_view}  |{ascii_view}|")


